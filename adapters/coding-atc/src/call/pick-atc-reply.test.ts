import { expect, test } from 'bun:test';
import { pickATCReply } from './pick-atc-reply';

test.each([
  {
    code: 'outcome_unknown',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'unknown',
    canClear: null,
  },
  {
    code: 'daemon_unavailable',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'unknown',
    canClear: null,
  },
  {
    code: 'no_such_session',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'unknown',
    canClear: null,
  },
  {
    code: 'daemon_unavailable',
    procedure: 'session.kill',
    isKeyed: false,
    status: 'refused',
    canClear: true,
  },
  {
    code: 'target_unavailable',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'refused',
    canClear: true,
  },
  {
    code: 'host_unavailable',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'refused',
    canClear: true,
  },
  { code: 'timeout', procedure: 'session.get', isKeyed: false, status: 'refused', canClear: true },
  {
    code: 'too_slow',
    procedure: 'session.submit',
    isKeyed: false,
    status: 'refused',
    canClear: true,
  },
  {
    code: 'permission_pending',
    procedure: 'session.submit',
    isKeyed: false,
    status: 'refused',
    canClear: true,
  },
  {
    code: 'host_leased',
    procedure: 'session.kill',
    isKeyed: false,
    status: 'refused',
    canClear: true,
  },
  {
    code: 'host_leased',
    procedure: 'session.get',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'idempotency_conflict',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'bad_args',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'target_forbidden',
    procedure: 'session.spawn',
    isKeyed: true,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'session_dead',
    procedure: 'session.submit',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'unsupported',
    procedure: 'session.read',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'no_such_session',
    procedure: 'session.get',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'insufficient_scope',
    procedure: 'session.kill',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'unauthorized',
    procedure: 'session.kill',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'daemon_unauthorized',
    procedure: 'session.get',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
  {
    code: 'protocol_mismatch',
    procedure: 'session.get',
    isKeyed: false,
    status: 'refused',
    canClear: true,
  },
  {
    code: 'something_new',
    procedure: 'session.get',
    isKeyed: false,
    status: 'refused',
    canClear: false,
  },
])('it maps $code on $procedure, keyed $isKeyed, to $status', (row) => {
  const reply = pickATCReply({ code: row.code, procedure: row.procedure, isKeyed: row.isKeyed });

  expect({
    status: reply.status,
    canClear: reply.status === 'refused' ? reply.canClear : null,
    reason: reply.reason,
  }).toStrictEqual({ status: row.status, canClear: row.canClear, reason: row.code });
});
