import { expect, test } from 'bun:test';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { nixieSchema } from './nixie-schema';
import { readBuiltTables } from './read-built-tables';
import { renderTableTypes } from './render-table-types';

test('it renders each column as the driver reads it, with null where the column allows it', () => {
  expect(
    renderTableTypes([
      {
        name: 'plants',
        columns: [
          { name: 'plant_id', type: 'text', isNullable: false },
          { name: 'height', type: 'real', isNullable: true },
          { name: 'photo', type: 'blob', isNullable: false },
          { name: 'bed_id', type: 'integer', isNullable: true },
        ],
      },
    ]),
  ).toMatchInlineSnapshot(`
    "// Generated by \`bun run --cwd libs/db tables\` from the migrations in nixieSchema. Do not edit.
    // A module's table types check against it through CheckedTables.
    export interface NixieTables {
      readonly plants: {
        readonly plant_id: string;
        readonly height: number | null;
        readonly photo: Uint8Array<ArrayBuffer>;
        readonly bed_id: number | null;
      };
    }
    "
  `);
});

test('it renders the same file from the same tables', () => {
  const tables = [
    { name: 'beds', columns: [{ name: 'bed_id', type: 'integer', isNullable: false }] },
  ];

  expect(renderTableTypes(tables)).toStrictEqual(renderTableTypes(tables));
});

test('it rejects a column type that has no TypeScript type', () => {
  expect(() =>
    renderTableTypes([
      { name: 'beds', columns: [{ name: 'planted_on', type: 'date', isNullable: false }] },
    ]),
  ).toThrowWithMessage(
    Error,
    "beds.planted_on has the column type 'date', which has no TypeScript type",
  );
});

// Run `bun run --cwd libs/db tables` to rewrite nixie-tables.ts after a migration.
test('it matches the committed nixie-tables.ts', async () => {
  const committed = await readFile(join(import.meta.dir, 'nixie-tables.ts'), 'utf8');
  const tables = await readBuiltTables(nixieSchema);

  expect(renderTableTypes(tables)).toBe(committed);
});
